//! The golden trama of layer 1: what `decide` proposes for every place of
//! the body (`hfd`) and every state before (`cyz`), with layer 0 as the key
//! (`rbh`). It is the cell `rbh.cyz : hfd : cyz` of the trama
//! `rbh.cyz:fv.hfd:rbh.cyz`, written with the digits of the white book
//! (volume II, ch. 05). Layer 1 reads neither `fv` nor layer 0's state before:
//! they are not in the table. If a rule changed on purpose, the test prints the
//! new trama to copy into `contract/bed-posture-frame.txt`.

use super::super::BedPostureState;
use super::decide;
use crate::belief::InBed;
use crate::body::HeadPlaceState;
use crate::refine::{BodyPlaces, DisparitySide, FeetPlace};

const GOLDEN: &str = include_str!("../../../../../../contract/bed-posture-frame.txt");

/// `cyz`: active, armed (believed lying once), risk.
const STATES: [(Option<BedPostureState>, &str); 5] = [
    (None, "000"),
    (Some(BedPostureState::InBed), "100"),
    (Some(BedPostureState::Lying), "110"),
    (Some(BedPostureState::SittingUp), "111"),
    (Some(BedPostureState::GettingOut), "112"),
];
/// `h`, ordered by risk.
const HEAD: [HeadPlaceState; 5] = [
    HeadPlaceState::Unknown,
    HeadPlaceState::AtHeadboard,
    HeadPlaceState::BelowHeadboard,
    HeadPlaceState::Elsewhere,
    HeadPlaceState::AtSide,
];
/// `f`: the feet as a set, and `?` for the camera's grey band.
const FEET: [(FeetPlace, char); 4] = [
    (FeetPlace::Unseen, '0'),
    (FeetPlace::Seen, '1'),
    (FeetPlace::PastTheSides, '2'),
    (FeetPlace::Doubtful, '?'),
];
/// `d`: the disparity, and `?` for the camera's grey band.
const DISPARITY: [(DisparitySide, char); 4] = [
    (DisparitySide::Unknown, '0'),
    (DisparitySide::Lying, '1'),
    (DisparitySide::Upright, '2'),
    (DisparitySide::Doubtful, '?'),
];

fn cyz(state: Option<BedPostureState>) -> &'static str {
    STATES
        .iter()
        .find(|(s, _)| *s == state)
        .map_or("???", |(_, digits)| digits)
}

/// Every place of the body, with its digits.
fn places() -> Vec<(String, BodyPlaces)> {
    let mut out = Vec::new();
    for (h, head) in HEAD.into_iter().enumerate() {
        for (feet, f) in FEET {
            for (disparity, d) in DISPARITY {
                let places = BodyPlaces {
                    head,
                    feet,
                    disparity,
                };
                out.push((format!("{h}{f}{d}"), places));
            }
        }
    }
    out
}

/// One row: what `decide` proposes from each state before.
fn row(l0: Option<InBed>, places: BodyPlaces) -> String {
    STATES
        .iter()
        .map(|(before, _)| cyz(decide(*before, l0, places.sighting())))
        .collect::<Vec<_>>()
        .join(" ")
}

fn trama() -> String {
    let mut out = String::from(
        "# The layer-1 trama. Generated by belief/bed_posture/rules/frame.rs.\n\
         # rbh[t] hfd | cyz[t] proposed from each cyz[t-1]: 000 100 110 111 112\n\
         # cyz: active · armed · risk (0 lying, 1 sitting up, 2 getting out)\n\
         # h: 0 unknown · 1 at headboard · 2 below headboard · 3 elsewhere · 4 at side\n\
         # f: 0 unseen · 1 seen · 2 past the sides (one out is out) · ? doubtful (not taken as out)\n\
         # d: 0 unknown · 1 lying · 2 upright · ? doubtful (the grey band: nothing new)\n\
         # *** : the row does not depend on the body (layer 0 decides)\n",
    );
    for (rbh, l0) in [("000", None), ("111", Some(InBed::Held))] {
        let rows: Vec<String> = places().into_iter().map(|(_, p)| row(l0, p)).collect();
        let first = rows.first().cloned().unwrap_or_default();
        assert!(
            rows.iter().all(|r| *r == first),
            "with rbh {rbh}, layer 1 must not depend on the body"
        );
        out += &format!("{rbh} *** | {first}\n");
    }
    for (digits, places) in places() {
        out += &format!("110 {digits} | {}\n", row(Some(InBed::Seen), places));
    }
    out
}

#[test]
fn layer_1_decides_as_the_golden_trama() {
    let trama = trama();
    assert!(
        trama == GOLDEN,
        "the layer-1 trama changed; if on purpose, copy it to contract/bed-posture-frame.txt:\n{trama}"
    );
}
